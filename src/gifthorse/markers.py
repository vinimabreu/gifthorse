"""Project markers that count only when their content confirms what they claim.

A package.json, a pyproject.toml or a Dockerfile makes the folder that holds it
a code project, and inside a project scripts and programs are judged more
leniently. Because that lowers a verdict, a marker counts only when its bytes
look like the real thing: an empty ``{}``, a requirements.txt of prose or an
empty Dockerfile adds nothing. A marker whose content was not read (names
only, encrypted, past a limit) never counts.
"""

from __future__ import annotations

import re
from collections.abc import Callable

from .jsonc import loads_jsonc

# Text validators read at most this much of a marker; markers are small. A JSON
# marker is parsed whole, already bounded by the per-file read limit.
_TEXT_LIMIT = 256 * 1024

_PYPROJECT = re.compile(r"(?m)^[ \t]*\[(?:project|build-system|tool(?:\.[^\]\n]{1,80})?)\][ \t]*$")
_SETUP_CFG = re.compile(r"(?m)^[ \t]*\[(?:metadata|options)\]")
_PKG_INFO = re.compile(r"(?m)^Metadata-Version:")
_CARGO = re.compile(r"(?m)^[ \t]*\[(?:package|workspace)\]")
_GO_MOD = re.compile(r"(?m)^module[ \t]+\S")
_GO_SUM = re.compile(r"(?m)^\S+ v\S+ h1:")
_GRADLE = re.compile(r"\b(?:plugins|apply|dependencies|repositories|android|allprojects)\b")
_GRADLE_SETTINGS = re.compile(r"\b(?:rootProject|include)\b")
_GEMFILE = re.compile(r"(?m)^[ \t]*(?:source|gem)[ \t]")
_PIPFILE = re.compile(r"(?m)^[ \t]*\[(?:packages|dev-packages|\[source\])\]")
_TOML_PACKAGE = re.compile(r"(?m)^\[\[package\]\]")
_TOX = re.compile(r"(?m)^[ \t]*\[(?:tox|testenv)")
_DOCKER_FROM = re.compile(r"(?im)^[ \t]*FROM[ \t]+\S")
_COMPOSE = re.compile(r"(?m)^services:")
_CMAKE = re.compile(r"(?i)\b(?:cmake_minimum_required|project)[ \t]*\(")
_MAKE_RULE = re.compile(r"(?m)^[A-Za-z0-9_.%/$()-]+(?:[ \t]+[A-Za-z0-9_.%/$()-]+)*[ \t]*::?(?!=)")
_JS_CONFIG = re.compile(r"\bexport\b|\bmodule\.exports\b|\bdefineConfig\b")
_AUTOCONF = re.compile(r"\bAC_INIT\b|\bAC_PREREQ\b|\bAM_INIT_AUTOMAKE\b")
_AUTOMAKE = re.compile(r"(?m)^[A-Za-z0-9_]+[ \t]*=|\bSUBDIRS\b|\b_SOURCES\b|\b_LDADD\b")
_MESON = re.compile(r"\bproject[ \t]*\(")
_CONFIGURE = re.compile(r"generated by GNU Autoconf|\bac_cs_version\b")
_MAKE_VARS = re.compile(r"(?m)^[A-Za-z0-9_]+[ \t]*=|^[A-Za-z0-9_.%/$()-]+[ \t]*::?(?!=)")
# One requirement: a name, optional extras, then a version, a URL or a marker.
_REQUIREMENT = re.compile(
    r"[A-Za-z0-9][A-Za-z0-9._-]*(?:[ \t]*\[[A-Za-z0-9._, \t-]*\])?"
    r"[ \t]*(?:(?:===|==|!=|~=|<=|>=|<|>|@)[ \t]*\S.*|;.*)?"
)


def _text(data: bytes) -> str:
    return data[:_TEXT_LIMIT].decode("utf-8", errors="replace")


def _json_has(data: bytes, keys: tuple[str, ...]) -> bool:
    parsed = loads_jsonc(data.decode("utf-8", errors="replace"))
    return isinstance(parsed, dict) and any(key in parsed for key in keys)


def _requirements(data: bytes) -> bool:
    for raw in _text(data).splitlines():
        line = raw.split(" #", 1)[0].strip()
        if not line or line.startswith(("#", "-")):
            continue
        if _REQUIREMENT.fullmatch(line):
            return True
    return False


def _search(pattern: re.Pattern[str]) -> Callable[[bytes], bool]:
    return lambda data: pattern.search(_text(data)) is not None


def _contains(*needles: str) -> Callable[[bytes], bool]:
    return lambda data: any(needle in _text(data) for needle in needles)


def _json_keys(*keys: str) -> Callable[[bytes], bool]:
    return lambda data: _json_has(data, keys)


# By lowercase file name. A name not listed here is not a marker.
_BY_NAME: dict[str, Callable[[bytes], bool]] = {
    "package.json": _json_keys("name", "scripts", "dependencies", "devDependencies"),
    "package-lock.json": _json_keys("lockfileVersion"),
    "pnpm-lock.yaml": _contains("lockfileVersion"),
    "yarn.lock": _contains("# yarn lockfile", "__metadata:"),
    "pyproject.toml": _search(_PYPROJECT),
    "setup.py": _contains("setup("),
    "setup.cfg": _search(_SETUP_CFG),
    "pkg-info": _search(_PKG_INFO),
    "requirements.txt": _requirements,
    "pipfile": _search(_PIPFILE),
    "poetry.lock": _search(_TOML_PACKAGE),
    "uv.lock": _search(_TOML_PACKAGE),
    "tsconfig.json": _json_keys("compilerOptions", "extends", "include", "files", "references"),
    "jsconfig.json": _json_keys("compilerOptions", "extends", "include", "files"),
    "deno.json": _json_keys("tasks", "imports", "compilerOptions", "name", "exports"),
    "composer.json": _json_keys("name", "require", "autoload"),
    "cargo.toml": _search(_CARGO),
    "go.mod": _search(_GO_MOD),
    "go.sum": _search(_GO_SUM),
    "pom.xml": _contains("<project"),
    "build.gradle": _search(_GRADLE),
    "build.gradle.kts": _search(_GRADLE),
    "settings.gradle": _search(_GRADLE_SETTINGS),
    "settings.gradle.kts": _search(_GRADLE_SETTINGS),
    "gradlew": _contains("gradle", "Gradle"),
    "gradlew.bat": _contains("gradle", "Gradle"),
    "gemfile": _search(_GEMFILE),
    "makefile": _search(_MAKE_RULE),
    "makefile.in": _search(_MAKE_VARS),
    "makefile.am": _search(_AUTOMAKE),
    "makefile.msc": _search(_MAKE_VARS),
    "configure.ac": _search(_AUTOCONF),
    "configure.in": _search(_AUTOCONF),
    "configure": _search(_CONFIGURE),
    "meson.build": _search(_MESON),
    "cmakelists.txt": _search(_CMAKE),
    "dockerfile": _search(_DOCKER_FROM),
    "docker-compose.yml": _search(_COMPOSE),
    "docker-compose.yaml": _search(_COMPOSE),
    "compose.yaml": _search(_COMPOSE),
    "tox.ini": _search(_TOX),
    "noxfile.py": _contains("import nox"),
    "vite.config.js": _search(_JS_CONFIG),
    "vite.config.ts": _search(_JS_CONFIG),
    "next.config.js": _search(_JS_CONFIG),
    "next.config.mjs": _search(_JS_CONFIG),
    "webpack.config.js": _search(_JS_CONFIG),
}
_BY_SUFFIX: dict[str, Callable[[bytes], bool]] = {
    ".csproj": _contains("<Project"),
    ".sln": _contains("Microsoft Visual Studio Solution File"),
}


def is_marker_name(name: str) -> bool:
    low = name.lower()
    return low in _BY_NAME or low.endswith(tuple(_BY_SUFFIX))


def confirms(name: str, data: bytes | None) -> bool:
    """Whether a marker file's content confirms that it is what its name says."""

    if data is None or not data.strip():
        return False
    low = name.lower()
    check = _BY_NAME.get(low)
    if check is None:
        check = next((v for k, v in _BY_SUFFIX.items() if low.endswith(k)), None)
    return check is not None and check(data)
